func pickName() string {
	if len(adjectives) == 0 || len(surnames) == 0 {
		return "anonymous"
	}

	adj := adjectives[rand.N(len(adjectives))]
	name := surnames[rand.N(len(surnames))]

	return fmt.Sprintf("%s_%s_%d", adj, name, rand.N(200))
}
